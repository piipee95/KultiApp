const assert=require('node:assert/strict');
const {boot}=require('./boot.cjs');
const dom=boot(),run=s=>dom.window.run(s);
assert.equal(run('printWearCost({hours:5,minutes:30,wear_rate_per_hour:100})'),550);
assert.equal(run('printWearCost({hours:1,minutes:0})'),0,'Legacy jobs retain zero wear');
assert.equal(run('printWearCost({hours:0,minutes:1,wear_rate_per_hour:100})'),2,'Round each print to CLP');
run(`newProduct();q('#addP').click();S.editorTab='prints';render();q('.ph').value=5;q('.pm').value=30;refresh();`);
assert.equal(run('S.product.prints[0].wear_rate_per_hour'),100);
assert.equal(run(`q('.wearAmount').textContent`),'$550');
assert.equal(run('totals().pc'),550);
run(`q('#qty').value=10;refresh()`);
assert.equal(run('totals().unit'),55,'Batch wear divided across product quantity');
run(`q('.wearRate').value=0;refresh()`);
assert.equal(run('totals().pc'),0);
run(`S.resources=[{id:'r1',kind:'printer',name:'Impresora ficticia',active:true,power_kw:0,wear_rate_per_hour:250}];render();q('.printerSelect').value='r1';q('.printerSelect').dispatchEvent(new Event('change'));`);
assert.equal(run('S.product.prints[0].wear_rate_per_hour'),250);
assert.equal(run('printWearCost(S.product.prints[0])'),1375);
run(`S.resources[0].wear_rate_per_hour=999`);
assert.equal(run('printWearCost(S.product.prints[0])'),1375,'Snapshot does not follow later printer edits');
run(`persistDraft();S.product=null;restoreDraft('new');render()`);
assert.equal(run('S.product.prints[0].wear_rate_per_hour'),250);
run(`S.product.additionalCosts[1].amount=100;render()`);
assert.ok(run(`!!q('#wearWarning')`),'Warn about existing manual wear');
run(`S.product.prints[0].wear_rate_per_hour=0;render()`);
assert.equal(run('totals().pc'),0);
assert.equal(run('totals().ac'),100,'Manual historical cost remains');
console.log('PASS desgaste: horas/minutos, CLP, lote, cero histórico, perfil, snapshot, borrador y desgaste manual');
